#!/usr/bin/env python3
"""gen_app5_stubs.py: give cinder-app5 a do-nothing export for every cinder.h function it does not
implement yet, so the shell links against it on the player while v0.5 is built a function at a time
(docs/PLAN_v0.5.md).

    python3 tools/gen_app5_stubs.py          rewrite player/cinder-app5/src/stubs.rs
    python3 tools/gen_app5_stubs.py --check  exit 1 if stubs.rs is out of date

A function counts as implemented when another .rs file in cinder-app5/src or cinder-core/src declares
`fn <name>(` or `getter!(<name>,` (settings.rs). Implement one, rerun this, and its stub disappears. Stubs return 0 or NULL, which is
also what cinder.h callers already treat as "not ready".
"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "player/cinder-ffi/include/cinder.h"
SRC = ROOT / "player/cinder-app5/src"
OUT = SRC / "stubs.rs"

# The same one-line declaration shape cinder-home/harness/gen_stubs.py reads.
DECL = re.compile(r'^\s*((?:const\s+)?'
                  r'(?:unsigned\s+long\s+long|unsigned\s+long|unsigned\s+int|unsigned\s+char'
                  r'|signed\s+char|unsigned|long\s+long|long|int|void|float|double|char|size_t)'
                  r'(?:\s*\*+)?)\s*\b([a-z_][a-z0-9_]*)\s*\(([^;]*)\)\s*;')

# cinder.h also declares a few that the C++ volume shim defines (cinder-audio/src/volume_shim.cpp).
SHELL_DEFINED = {'cinder_volume_avls_enabled', 'cinder_volume_avls_threshold',
                 'cinder_volume_service_set'}

BASE = {'int': 'libc::c_int', 'unsigned': 'libc::c_uint', 'unsigned int': 'libc::c_uint',
        'long long': 'libc::c_longlong', 'unsigned long long': 'u64', 'float': 'f32',
        'char': 'libc::c_char', 'signed char': 'libc::c_schar', 'unsigned char': 'libc::c_uchar',
        'void': 'libc::c_void'}


def rust_type(c):
    c = c.strip()
    const = c.startswith('const ')
    c = c[6:].strip() if const else c
    ptr = c.count('*')
    base = BASE[c.replace('*', '').strip()]
    for _ in range(ptr):
        base = ('*const ' if const else '*mut ') + base
        const = False
    return base


def decls():
    for line in HEADER.read_text().split('\n'):
        m = DECL.match(line)
        if not m or not m.group(2).startswith('cinder_'):
            continue
        rt, name, args = m.group(1), m.group(2), m.group(3).strip()
        params = []
        if args and args != 'void':
            for i, a in enumerate(args.split(',')):
                a = a.strip()
                t = re.sub(r'\s*\b[a-z_][a-z0-9_]*$', '', a) if re.search(r'[a-z_]\s*$', a) and ' ' in a else a
                params.append(f"_a{i}: {rust_type(t)}")
        yield name, rt.strip(), params


def render():
    done = set()
    # cinder-core's own exports link into app5 too (the library index switches, flac).
    for f in [*SRC.glob('*.rs'), *(ROOT / 'player/cinder-core/src').glob('*.rs')]:
        if f.name != 'stubs.rs':
            done |= set(re.findall(r'(?:\bfn |\bgetter!\()(cinder_[a-z0-9_]+)\s*[(,]', f.read_text()))
    out = ['//! GENERATED by tools/gen_app5_stubs.py. Do not edit: implement the function elsewhere in',
           '//! this crate and rerun the script. Each stub is a cinder.h export v0.5 does not do yet.',
           '#![allow(clippy::missing_safety_doc)]', '']
    seen = set()
    for name, rt, params in decls():
        if name in done or name in seen or name in SHELL_DEFINED:
            continue
        seen.add(name)
        ret = '' if rt == 'void' else f" -> {rust_type(rt)}"
        body = '' if rt == 'void' else ('std::ptr::null_mut()' if '*' in rt else ('0.0' if rt == 'float' else '0'))
        out.append('#[no_mangle]')
        out.append(f"pub unsafe extern \"C\" fn {name}({', '.join(params)}){ret} {{")
        if body:
            out.append(f"    {body}")
        out.append('}')
    # Formatted the way `cargo fmt` would leave it, so --check and the fmt CI step agree.
    return subprocess.run(['rustfmt', '--edition', '2021', '--emit', 'stdout'],
                          input='\n'.join(out) + '\n', capture_output=True, text=True,
                          check=True).stdout


def main():
    text = render()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            print("cinder-app5/src/stubs.rs is out of date: run tools/gen_app5_stubs.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"{text.count('#[no_mangle]')} stubs written to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
